import 'package:flutter/widgets.dart';

enum _Bucket { phone, sw600, sw720 }

/// Scalable dimensions ported from the project's Android `sdp`/`ssp`
/// resource tables (`values/dimens.xml`, `values-sw600dp/dimens.xml` and
/// `values-sw720dp/dimens.xml`). Values switch between the three tables
/// based on screen width, mirroring how Android resolves resource
/// qualifiers (the widest matching bucket wins).
class AppDimens {
  AppDimens._();

  static const double sw600Breakpoint = 600;
  static const double sw720Breakpoint = 720;

  static _Bucket _bucketOf(BuildContext context) {
    final width = MediaQuery.sizeOf(context).width;
    if (width >= sw720Breakpoint) return _Bucket.sw720;
    if (width >= sw600Breakpoint) return _Bucket.sw600;
    return _Bucket.phone;
  }

  static bool isTablet(BuildContext context) =>
      MediaQuery.sizeOf(context).width >= sw600Breakpoint;

  /// Scalable dp value, e.g. `AppDimens.sdp(context, '_24sdp')`.
  static double sdp(BuildContext context, String key) {
    final table = switch (_bucketOf(context)) {
      _Bucket.sw720 => _sw720Sdp,
      _Bucket.sw600 => _sw600Sdp,
      _Bucket.phone => _phoneSdp,
    };
    return table[key] ?? _phoneSdp[key] ?? 0;
  }

  /// Scalable sp (font size) value, e.g. `AppDimens.ssp(context, '_14ssp')`.
